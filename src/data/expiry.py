"""Generate config/expiry_dates.csv from the sessions in the minute file.

Usage: python -m src.data.expiry

The calendar marks a weekly expiry on every Thursday up to 2025-08-28 and every Tuesday
from 2025-09-02, the dates of the NSE switch. If the scheduled day is a market holiday,
the expiry moves to the previous session. Nifty weekly options only began in 2019, so
Thursdays before that are a project choice and not actual NSE weekly expiries.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from src.config import EXPIRY_FILE, REAL_PATHS
from src.data.bars import daily_from_minute
from src.data.features import weekday_index
from src.data.loaders import load_minute

LAST_THURSDAY_EXPIRY = np.datetime64("2025-08-28")
FIRST_TUESDAY_EXPIRY = np.datetime64("2025-09-02")
TUESDAY, THURSDAY = 1, 3


def weekly_expiry_dates(sessions: np.ndarray) -> np.ndarray:
    """Expiry dates within the span of the given sorted trading sessions."""
    days = np.arange(sessions[0], sessions[-1] + 1)
    weekdays = weekday_index(days)
    scheduled = days[
        ((weekdays == THURSDAY) & (days <= LAST_THURSDAY_EXPIRY))
        | ((weekdays == TUESDAY) & (days >= FIRST_TUESDAY_EXPIRY))
    ]
    # Latest session on or before each scheduled day. Sessions[0] is the span start, so
    # every scheduled day has one.
    previous = np.searchsorted(sessions, scheduled, side="right") - 1
    return np.unique(sessions[previous])


def write_expiry_file(expiry_dates: np.ndarray, path: Path = EXPIRY_FILE) -> None:
    lines = [
        "# Weekly schedule: Thursdays to 2025-08-28, Tuesdays from 2025-09-02, moved to the",
        "# previous session on holidays. Generated by: python -m src.data.expiry",
        "date",
        *(str(d) for d in expiry_dates),
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    daily, dropped = daily_from_minute(load_minute(REAL_PATHS.raw))
    # A thin session is still a session, so an expiry can fall on it.
    sessions = np.union1d(daily.dates, dropped.dates[dropped.n_bars > 0])
    dates = weekly_expiry_dates(sessions)
    write_expiry_file(dates)
    print(f"Wrote {dates.size} expiry dates, {dates[0]} to {dates[-1]}, to {EXPIRY_FILE}")


if __name__ == "__main__":
    main()
